import { readFileSync, writeFileSync } from "node:fs";
import { themeTokens } from "../src/theme/tokens";

const resolve = (value: string, theme: Record<string, string>): string =>
  value.replace(/var\(--([\w-]+)\)/g, (_, name: string) => resolve(theme[name] ?? "", theme));
const dom = Object.entries(themeTokens)
  .map(
    ([theme, tokens]) =>
      `${theme === "light" ? ":root" : '.dark, [data-theme="dark"]'} {\n${Object.entries(tokens)
        .map(([key, value]) => `  --${key}: ${value};`)
        .join("\n")}\n}`,
  )
  .join("\n\n");
const native = `@layer theme {\n  :root {\n${Object.entries(themeTokens)
  .map(
    ([theme, tokens]) =>
      `    @variant ${theme} {\n${Object.entries(tokens)
        .filter(([key]) => !key.startsWith("shadow") && key !== "radius")
        .map(([key, value]) => `      --color-${key}: ${resolve(value, tokens)};`)
        .join("\n")}\n    }`,
  )
  .join("\n")}\n  }\n}\n`;
const files = { "theme.css": dom + "\n", "native.css": native };
for (const [name, content] of Object.entries(files)) {
  const target = new URL(`../src/styles/${name}`, import.meta.url);
  const generated = "/* Generated by ui generate:theme. Edit src/theme/tokens.ts. */\n" + content;
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== generated)
      throw new Error(`Outdated theme artifact: ${name}`);
  } else writeFileSync(target, generated);
}
