import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { apiExposure } from "@raypx/contracts/api";
import { localParams } from "@raypx/contracts/local";
import { messages } from "@raypx/i18n/messages";
import { DESKTOP_METHODS } from "../../bridge";

export async function generateNativeContracts(desktop: string, check = false) {
  const directory = resolve(desktop, "generated");
  const artifacts: Record<string, unknown> = {
    "desktop-methods.json": DESKTOP_METHODS,
    "local-methods.json": Object.keys(localParams).sort(),
    "notifications.json": {
      en: messages.en.tasks.notification,
      zh: messages.zh.tasks.notification,
    },
  };
  for (const [file, value] of Object.entries(artifacts)) {
    const path = resolve(directory, file);
    const source = JSON.stringify(value, null, 2) + "\n";
    if (!check && (await readFile(path, "utf8").catch(() => "")) !== source) {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, source);
    }
  }

  const paths = (exposure: "renderer" | "native") =>
    Object.entries(apiExposure)
      .flatMap(([group, methods]) =>
        Object.entries(methods)
          .filter(([, value]) => value === exposure)
          .map(([method]) => `/rpc/${group}/${method}`),
      )
      .sort();
  const slice = (name: string, values: string[]) =>
    `var ${name} = []string{\n${values.map((path) => `\t${JSON.stringify(path)},`).join("\n")}\n}\n`;
  const source =
    "// Code generated by native:generate. DO NOT EDIT.\n\npackage desktop\n\n" +
    slice("rpcPaths", paths("renderer")) +
    "\n" +
    slice("nativeRPCPaths", paths("native"));
  const path = resolve(desktop, "internal/desktop/rpc_paths.generated.go");
  if (check) {
    if ((await readFile(path, "utf8")) !== source)
      throw new Error("Regenerate native RPC policy with native:generate");
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, source);
  }
}
if (import.meta.main)
  await generateNativeContracts(
    resolve(import.meta.dirname, "../.."),
    process.argv.includes("--check"),
  );
